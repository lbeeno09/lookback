bool Application::Initialize(GraphicsRenderer::GraphicsAPI api)
{
	m_selectedGraphicsAPI = api;

	glfwSetErrorCallback(GlfwErrorCallback);
	if(!glfwInit())
	{
		std::cerr << "Application: Failed to initialize GLFW" << std::endl;
		return false;
	}

	if(m_selectedGraphicsAPI == GraphicsRenderer::GraphicsAPI::OpenGL)
	{
		// Decide GL+GLSL versions
		// GL 3.0 + GLSL 330
		const char *glsl_version = "#version 330";
		glfwWindowHint(GLFW_CONTEXT_VERSION_MAJOR, 3);
		glfwWindowHint(GLFW_CONTEXT_VERSION_MINOR, 3);
		glfwWindowHint(GLFW_OPENGL_PROFILE, GLFW_OPENGL_CORE_PROFILE);
		glfwWindowHint(GLFW_OPENGL_FORWARD_COMPAT, GL_TRUE);
	}

	// Create window with graphics context
	m_window = glfwCreateWindow(1280, 720, "Look Back", nullptr, nullptr);
	if(!m_window)
	{
		std::cerr << "Application: Failed to create GLFW window" << std::endl;
		glfwTerminate();
		return false;
	}
	glfwMakeContextCurrent(window);
	glfwSwapInterval(1);

}

